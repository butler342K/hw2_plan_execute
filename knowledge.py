import os
from pathlib import Path

import chromadb
from chromadb.utils.embedding_functions import OpenAIEmbeddingFunction
from dotenv import load_dotenv
from langchain_core.tools import tool

load_dotenv()

# ── Створення бази знань ─────────────────────────────────────────
# Дефолтна ONNX-модель ChromaDB (all-MiniLM-L6-v2) навчена переважно на
# англійській і погано розрізняє семантику українських речень — близькі за
# лексикою, але різні за змістом документи (наприклад, "вартість доставки
# за кордон" і "вартість доставки Новою Поштою за об'ємною вагою")
# плутаються в топ-3. OpenAI text-embedding-3-small багатомовна і дає
# набагато релевантніший пошук для українських запитів.
embedding_fn = OpenAIEmbeddingFunction(
    api_key=os.getenv('OPENAI_API_KEY'),
    model_name='text-embedding-3-small',
)

# Персистентне сховище поруч з agent_state.db (той файл — окрема SQLite-база
# LangGraph checkpointer-а з власною схемою (checkpoints/writes), тому
# ChromaDB не може писати в нього напряму: PersistentClient керує власною
# директорією (chroma.sqlite3 + бінарні файли HNSW-індексу на колекцію).
CHROMA_DIR = Path(__file__).parent / 'chroma_db'
chroma_client = chromadb.PersistentClient(path=str(CHROMA_DIR))
knowledge_base = chroma_client.get_or_create_collection(
    'domain_knowledge', embedding_function=embedding_fn
)
 
# Документи для вашої доменної області (≥8 штук)
documents = [
    "Ортопедичні матраси виготовляються під замовлення. Термін виготовлення: 5-7 днів. ",
    "Доставка за кордон виконується Укрпоштою. Вартість доставки залежить від країни та ваги посилки.",
    "Доставка за кордон може бути здійснена Новою Поштою якщо в країні є представництво компанії. Вартість доставки залежить від країни та ваги посилки.",
    "Затримка доставки за кордон може бути пов'язана з митними процедурами та перевіркою документів.",
    "Затримка доставки по Україні може бути через непередбачувані затримки в зв'язку з військовими діями та озброєнною агресією росії.",
    "Затримка відправки замовлення може бути через ускладнену логістику в зв'язку з військовими діями та озброєнною агресією росії. Відслідковуйте статус замовлення в цьому чат-боті.",
    "Вартість доставки Новою Поштою визначається за об'ємною вагою посилки. Об'ємна вага розраховується за формулою: (довжина * ширина * висота) / 4000.",
    "Якщо ви вважаєте, що об'ємна вага вашої посилки розрахована неправильно, зверніться до оператора у відділенні Нової Пошти. Він допоможе вам перевірити правильність розрахунку та, за потреби, зробити повторний розрахунок.",
    "Перевіряйте цілісніть товару у відділенні Нової Пошти. Якщо товар пошкоджений, зверніться до оператора і оформіть акт про пошкодження. Після цього зв'яжіться з нами для вирішення питання щодо повернення або заміни товару.",
    "Якщо товар не підійшов вам за розміром, кольором або іншими характеристиками, ви можете зробити легке повернення Новою Поштою. Ця послуга безкоштовна для вас. Зверніть увагу, що має бути збережено товарний вигляд та упаковка.",
]
doc_ids = [f'doc_{i}' for i in range(len(documents))]
 
knowledge_base.upsert(documents=documents, ids=doc_ids)
print(f'Knowledge base: {knowledge_base.count()} documents loaded')
 
# ── RAG Tool ─────────────────────────────────────────────────────
@tool
def search_knowledge(query: str) -> str:
    """Пошук інформації у базі знань.
 
    Використовуйте цей інструмент, коли потрібна довідкова
    інформація, факти, правила або рекомендації з бази знань.
    НЕ використовуйте для обчислень або дій.
 
    Args:
        query: Пошуковий запит.
 
    Returns:
        Топ-3 релевантних документи з бази знань.
    """
    results = knowledge_base.query(query_texts=[query], n_results=3)
    docs = results['documents'][0]
    return '\n---\n'.join(docs)
 
# ── Unit test ────────────────────────────────────────────────────
if __name__ == '__main__':
    print('Query: чому затримується доставка за кордон')
    result = search_knowledge.invoke({'query': 'чому затримується доставка за кордон'})
    print(f'RAG result:\n{result}')

    print('\nQuery: Яка вартість доставки Новою Поштою')
    result = search_knowledge.invoke({'query': 'яка вартість доставки Новою Поштою'})
    print(f'RAG result:\n{result}')